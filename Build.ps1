# Builds dist\API-Tester.ps1 from src\ and writes dist\API-Tester.ps1.sha256 (used by the in-app updater).
# Exit code 1 when the compiled script has syntax errors, so CI (and any release script) can stop.
$ErrorActionPreference = "Stop"

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$srcDir    = Join-Path $scriptDir "src"
$distDir   = Join-Path $scriptDir "dist"
$outFile   = Join-Path $distDir "API-Tester.ps1"

if (-not (Test-Path $distDir)) {
    New-Item -ItemType Directory -Path $distDir | Out-Null
}

if (Test-Path $outFile) {
    Remove-Item $outFile -Force
}

# The specific order is crucial to ensure functions are defined before they are called
$filesToMerge = @(
    "Parameters.ps1"
    "Config\Constants.ps1"
    
    "Utils\Helpers.ps1"
    "Utils\Formatting.ps1"
    
    "UI\Controls.ps1"
    "UI\WpfHost.ps1"
    "UI\ThemeRenderer.ps1"
    
    "Core\StateManager.ps1"
    "Core\Auth.ps1"
    "Core\HttpClient.ps1"
    "Core\TestRunner.ps1"
    "Core\OpenApiParser.ps1"
    "Core\Importers.ps1"
    "Core\RequestService.ps1"
    "Core\ScriptRunner.ps1"
    "Core\CodeGenerator.ps1"
    "Core\ReportBuilder.ps1"
    "Core\Inheritance.ps1"
    "Core\Secrets.ps1"
    "Core\Exporters.ps1"
    "Core\RunnerReport.ps1"
    "Core\AlertChannels.ps1"
    "Core\Updater.ps1"
    
    # Dialogs can be loaded in any order as long as they are before MainForm
    "UI\Dialogs\AboutDialog.ps1"
    "UI\Dialogs\AuthPanel.ps1"
    "UI\Dialogs\CookieJar.ps1"
    "UI\Dialogs\DiffViewer.ps1"
    "UI\Dialogs\EnvironmentEditor.ps1"
    "UI\Dialogs\EnvironmentManagerWindow.ps1"
    "UI\Dialogs\GrpcClient.ps1"
    "UI\Dialogs\JwtTool.ps1"
    "UI\Dialogs\LoadTester.ps1"
    "UI\Dialogs\LogViewer.ps1"
    "UI\Dialogs\MonitorChartWindow.ps1"
    "UI\Dialogs\MonitorEditor.ps1"
    "UI\Dialogs\MonitorEmailSettings.ps1"
    "UI\Dialogs\MonitorManager.ps1"
    "UI\Dialogs\MonitoringDashboard.ps1"
    "UI\Dialogs\ProxySettings.ps1"
    "UI\Dialogs\ReportGenerator.ps1"
    "UI\Dialogs\SettingsWindow.ps1"
    "UI\Dialogs\VariablesEditor.ps1"
    "UI\Dialogs\WebSocketClient.ps1"
    
    "UI\NewCharts.ps1"
    "UI\NewCodeEditor.ps1"
    "UI\NewMenuBar.ps1"
    "UI\NewRequestEditor.ps1"
    "UI\NewSidebar.ps1"
    "UI\NewDialogs.ps1"
    "UI\NewToolDialogs.ps1"
    "UI\NewNetworkDialogs.ps1"
    "UI\NewMonitorUi.ps1"
    "UI\NewMainWindow.ps1"
    "UI\MainForm.ps1"
    "Main.ps1" # The very bottom invocation: New-ApiForm
)

# Every source file must be present. An update archive that contains only changed files has to be copied over the
# complete repository first - building it on its own cannot work.
$missingFiles = @($filesToMerge | Where-Object { -not (Test-Path (Join-Path $srcDir $_)) })
if ($missingFiles.Count -gt 0) {
    Write-Host "Cannot build: $($missingFiles.Count) of $($filesToMerge.Count) source files are missing in $srcDir" -ForegroundColor Red
    $missingFiles | Select-Object -First 8 | ForEach-Object { Write-Host "  - src\$_" -ForegroundColor Red }
    if ($missingFiles.Count -gt 8) { Write-Host "  ... and $($missingFiles.Count - 8) more" -ForegroundColor Red }
    Write-Host ''
    Write-Host 'Run Build.ps1 in the complete API Tester folder (your git clone). If you received an archive with only the' -ForegroundColor Yellow
    Write-Host 'changed files, extract it over that folder first, for example:' -ForegroundColor Yellow
    Write-Host '  Expand-Archive .\API-Tester-ui-fixes.zip -DestinationPath C:\path\to\API-Tester -Force' -ForegroundColor Yellow
    exit 1
}

$constantsText = [System.IO.File]::ReadAllText((Join-Path $srcDir "Config\Constants.ps1"), [System.Text.Encoding]::UTF8)
$appVersion = if ($constantsText -match '\$script:AppVersion\s*=\s*"([^"]+)"') { $Matches[1] } else { "unknown" }

$outBuffer = New-Object System.Text.StringBuilder

# Add header
$outBuffer.AppendLine("# PowerShell API Tester v$appVersion (compiled build)") | Out-Null
$outBuffer.AppendLine("# This file is auto-generated by Build.ps1. Do not edit directly.") | Out-Null
$outBuffer.AppendLine() | Out-Null

foreach ($relPath in $filesToMerge) {
    $fullPath = Join-Path $srcDir $relPath
    if (Test-Path $fullPath) {
        Write-Host "Merging: $relPath"
        $content = [System.IO.File]::ReadAllText($fullPath, [System.Text.Encoding]::UTF8)
        $outBuffer.AppendLine($content) | Out-Null
    } else {
        Write-Warning "File not found: $fullPath"
    }
}

[System.IO.File]::WriteAllText($outFile, $outBuffer.ToString(), [System.Text.Encoding]::UTF8)

Write-Host "`nBuild complete: $outFile"
Write-Host "Running syntax check on the compiled file..."

$errors = $null
$null = [System.Management.Automation.Language.Parser]::ParseFile($outFile, [ref]$null, [ref]$errors)

if ($errors.Count -gt 0) {
    Write-Host "Syntax errors found:" -ForegroundColor Red
    foreach ($err in $errors) {
        Write-Host "Line $($err.Extent.StartLineNumber): $($err.Message)" -ForegroundColor Red
    }
    exit 1
}
Write-Host "Syntax OK." -ForegroundColor Green

# Checksum published next to the script in each GitHub release; the updater refuses a download that does not match.
$hash = (Get-FileHash -Path $outFile -Algorithm SHA256).Hash.ToLowerInvariant()
[System.IO.File]::WriteAllText("$outFile.sha256", "$hash  API-Tester.ps1", [System.Text.Encoding]::ASCII)
Write-Host "Version : $appVersion"
Write-Host "SHA-256 : $hash"
exit 0
